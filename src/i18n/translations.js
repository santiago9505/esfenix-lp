export function translateText(value) {
  const text = String(value ?? '');
  if (Object.hasOwn(ES, text)) return ES[text];
  if (countryNames.has(text)) return countryNames.get(text);
  for (const [pattern, replacement] of dynamic) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  if (text.endsWith(' *')) return `${translateText(text.slice(0, -2))} *`;
  for (const separator of [' · ', ' — ']) {
    if (text.includes(separator)) {
      const translated = text.split(separator).map(translateText).join(separator);
      if (translated !== text) return translated;
    }
  }
  return text;
}

/**
 * Imports the delivered flower photography as optimized, local fallback
 * assets and generates the manifest consumed by the runtime catalog.
 *
 * Usage:
 *   node scripts/import-local-product-images.mjs "C:\\path\\to\\FLOWERS"
 */

import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourceArgument = process.argv[2];
if (!sourceArgument) {
  throw new Error('Pass the source image directory as the first argument.');
}
const sourceRoot = resolve(sourceArgument);
const outputRoot = resolve(ROOT, 'public/assets/images/flowers-fallback');
const manifestPath = resolve(ROOT, 'src/catalog/data/local-product-images.js');
const supportedExtensions = /\.(png|jpe?g|webp|gif|avif)$/i;

if (!sourceRoot || !statSafe(sourceRoot)?.isDirectory()) {
  throw new Error(`Image source directory not found: ${sourceRoot}`);
}

function statSafe(file) {
  try {
    return statSync(file);
  } catch {
    return null;
  }
}

function walk(dir, files = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = join(dir, entry.name);
    if (entry.isDirectory()) walk(file, files);
    else if (supportedExtensions.test(entry.name)) files.push(file);
  }
  return files;
}

function slugify(value) {
  return String(value ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'flower';
}

function normalize(value) {
  return String(value ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

function classify(stem) {
  const value = normalize(stem);
  const gardenMatch = value.match(/^(?:garden|graden)\s+(?:roses|rouses)\s+(.+)$/);
  if (gardenMatch) return { family: 'garden', key: gardenMatch[1] };

  const rosesMatch = value.match(/^roses\s+(.+)$/);
  if (rosesMatch) return { family: 'standard', key: rosesMatch[1] };

  return { family: 'standard', key: value };
}

const files = walk(sourceRoot).sort((a, b) => a.localeCompare(b));
if (files.length === 0) throw new Error(`No supported images found in: ${sourceRoot}`);

mkdirSync(outputRoot, { recursive: true });
const entries = [];
const usedNames = new Set();

for (const file of files) {
  const stem = basename(file, extname(file));
  const baseName = slugify(stem);
  let outputName = `${baseName}.webp`;
  let suffix = 2;
  while (usedNames.has(outputName)) outputName = `${baseName}-${suffix++}.webp`;
  usedNames.add(outputName);

  const outputPath = join(outputRoot, outputName);
  const optimized = sharp(file)
    .rotate()
    .resize({ width: 1600, height: 1200, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: 82, effort: 6, smartSubsample: true });
  await optimized.toFile(outputPath);

  await sharp(outputPath)
    .resize({ width: 240, height: 180, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: 74, effort: 6, smartSubsample: true })
    .toFile(outputPath.replace(/\.webp$/i, '-thumb.webp'));

  const classification = classify(stem);
  entries.push({
    id: `local-${slugify(relative(sourceRoot, file))}`,
    family: classification.family,
    key: classification.key,
    originalName: stem,
    src: `/assets/images/flowers-fallback/${outputName}`,
  });
}

entries.sort((a, b) => a.src.localeCompare(b.src));

const manifest = `/**\n * Generated by scripts/import-local-product-images.mjs.\n * These assets are used only when Fresa has no usable product image.\n */\nexport const LOCAL_PRODUCT_IMAGES = ${JSON.stringify(entries, null, 2)};\n`;
writeFileSync(manifestPath, manifest);

console.log(`Imported ${entries.length} local product images.`);
console.log(`Manifest: ${manifestPath}`);
console.log(`Assets:   ${outputRoot}`);
